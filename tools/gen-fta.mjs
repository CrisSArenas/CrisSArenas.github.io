// One-off generator for the Fund Terms Auditor's synthetic fund (fictional Ostrel Capital Partners VI):
// writes assets/data/fta-fund.js (fund-level deals and portfolio fees) and assets/data/fta-docs.js (LPA excerpt
// and four ILPA-style quarterly reports, with three planted breaks). The hand-set labels are written separately.
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const PM = require('../assets/js/pm-math.js');
const root = new URL('..', import.meta.url).pathname;
const D = s => new Date(s + 'T00:00:00Z');
const deals = [
  ['2019-12-15', 90, '2023-09-30', 171], ['2020-03-20', 85, '2024-06-30', 140], ['2020-08-10', 110, '2025-03-31', 165], ['2020-12-05', 75, null, 98],
  ['2021-04-22', 95, '2025-12-31', 118], ['2021-09-14', 80, null, 92], ['2022-02-03', 105, null, 104], ['2022-07-19', 70, '2026-03-31', 96],
  ['2022-11-30', 90, null, 101], ['2023-05-11', 85, null, 88], ['2023-10-25', 100, null, 112], ['2024-04-18', 65, null, 70]
].map((d, i) => ({ id: 'D' + (i + 1), invest: d[0], cost: d[1], exit: d[2], value: d[3] }));
const SIZE = 1200, SHARE = 45 / 1200, IP_END = D('2024-10-15'), CLOSE = D('2019-10-15'), LINE_DAYS = 180, ASOF = D('2026-06-30');
const pfees = { '2025-09-30': 1.6, '2025-12-31': 0.9, '2026-03-31': 2.8, '2026-06-30': 0.6 };
// quarterly fee schedule, fund level
const qEnds = []; for (let y = 2019; y <= 2026; y++) for (const m of ['03-31', '06-30', '09-30', '12-31']) { const d = D(y + '-' + m); if (d > CLOSE && d <= ASOF) qEnds.push(d); }
const nic = d => deals.filter(x => D(x.invest) < d && (!x.exit || D(x.exit) >= d)).reduce((s, x) => s + x.cost, 0);
const feeRows = qEnds.map(q => { const start = new Date(q.getTime() - 89 * 864e5); const inIP = start < IP_END; const n = nic(start); const k = q.toISOString().slice(0, 10); return { q: k, inIP, nic: n, gross: (inIP ? 0.02 * SIZE : 0.015 * n) / 4, pfee: pfees[k] || 0.4 }; });
const fund = { size: SIZE, lpCommitment: 45, lpShare: SHARE, close: '2019-10-15', ipEnd: '2024-10-15', lineDays: LINE_DAYS, asOf: '2026-06-30', deals, fees: feeRows.map(f => ({ q: f.q, inIP: f.inIP, nic: f.nic, portfolioFees: f.pfee })), expensesPerQuarter: 0.35 };
fs.writeFileSync(root + 'assets/data/fta-fund.js', '/* Fictional fund for the Fund Terms Auditor (Ostrel Capital Partners VI). Fund-level $m. Generated by tools/gen-fta.mjs. */\nwindow.FTA_FUND = ' + JSON.stringify(fund) + ';\n');
const f = (x, d = 0) => '$' + x.toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d });
const lpFee = r => r.gross * SHARE, lpOff = r => Math.min(r.gross, r.pfee) * SHARE;
const Q = feeRows.slice(-4);
// planted breaks: Q3 2025 fee on commitments at the post-period rate; Q1 2026 offset at 50%; Q2 2026 carry accrued with no hurdle
const rep = Q.map((r, i) => { let g = lpFee(r), o = lpOff(r); if (i === 0) g = 0.015 * SIZE / 4 * SHARE; if (i === 2) o = o / 2; const $ = v => Math.round(v * 1e6) / 1e6; return { q: r.q, gross: g, off: o, net: $(g) - $(o), nic: r.nic, pfee: r.pfee }; }); // net ties to the rounded lines, as a report prints it
// LP cash flows as charged (the reported fee in the last four quarters), with the subscription line, and the GP's naive accrued carry
const lp = [];
deals.forEach(d => { lp.push({ date: new Date(D(d.invest).getTime() + LINE_DAYS * 864e5), c: d.cost * SHARE }); if (d.exit && D(d.exit) <= ASOF) lp.push({ date: D(d.exit), dist: d.value * SHARE }); });
feeRows.forEach(fr => { const r = rep.find(x => x.q === fr.q); lp.push({ date: D(fr.q), c: r ? r.net + 0.35 * SHARE : (fr.gross - Math.min(fr.gross, fr.pfee) + 0.35) * SHARE }); });
const contrib = lp.filter(x => x.c).reduce((s, x) => s + x.c, 0), dist = lp.filter(x => x.dist).reduce((s, x) => s + x.dist, 0);
const navFund = deals.filter(d => !d.exit || D(d.exit) > ASOF).reduce((s, d) => s + d.value, 0), nav = navFund * SHARE;
const naiveCarry = 0.2 * Math.max(0, dist + nav - contrib);
// reported performance: the GP's own numbers, net of its (wrong) accrued carry, with the line in place
const perfFlows = lp.map(x => ({ date: x.date, amount: x.c ? -x.c : x.dist })).concat([{ date: ASOF, amount: nav - naiveCarry }]);
const perf = { irr: PM.xirr(perfFlows), tvpi: (dist + nav - naiveCarry) / contrib, dpi: dist / contrib };
const labels = ['Q3 2025', 'Q4 2025', 'Q1 2026', 'Q2 2026'];
const docs = {};
docs['lpa'] = { title: 'Ostrel Capital Partners VI, LPA excerpt', kind: 'lpa', pages: [[
  '# Ostrel Capital Partners VI, L.P. | Limited Partnership Agreement (excerpt)',
  'Fictional fund. Initial Closing Date: 15 October 2019. Total commitments: $1,200 million.',
  '',
  'Section 8.1 Management Fee',
  'During the Investment Period, an annual fee of 2.0% of total Commitments, payable quarterly.',
  'After the Investment Period, an annual fee of 1.5% of Net Invested Capital, payable quarterly,',
  'where Net Invested Capital is the cost of Portfolio Investments not yet realized or written off,',
  'measured at the start of each quarter.',
  'The Investment Period ends on the fifth anniversary of the Initial Closing Date.',
  '',
  'Section 8.2 Fee Offsets',
  'The Management Fee shall be reduced by 100% of the Partnership\'s share of Transaction Fees,',
  'Monitoring Fees and Directors\' Fees received in the quarter.'
], [
  'Section 9.1 Distributions (whole-fund waterfall)',
  'Distributable proceeds shall be applied in the following order:',
  '(a) first, 100% to the Limited Partners until they have received their Capital Contributions;',
  '(b) second, 100% to the Limited Partners until they have received a preferred return of 8%',
  'per annum, compounded annually, on their unreturned Capital Contributions;',
  '(c) third, 100% to the General Partner until it has received 20% of the sum distributed under (b) and (c);',
  '(d) thereafter, 80% to the Limited Partners and 20% to the General Partner.',
  '',
  'Section 9.4 Carried interest accrual',
  'Accrued carried interest shall be reported as the amount the General Partner would receive under',
  'Section 9.1 if the Partnership were liquidated at its reported net asset value.'
]] };
rep.forEach((r, i) => {
  const id = 'rpt-' + labels[i].replace(' ', '-').toLowerCase();
  const lines = [
    '# Ostrel Capital Partners VI, L.P. | Quarterly report, ' + labels[i],
    'Prepared in the ILPA Reporting Template format. Limited Partner: Fictional Endowment Fund.',
    'LP commitment: $45,000,000 (3.75% of the fund). Amounts in U.S. dollars, LP share unless stated.',
    '',
    'Management fee reconciliation',
    '| Fund net invested capital at start of quarter (fund level)    ' + f(r.nic * 1e6),
    '| Management fee, gross                                          ' + f(r.gross * 1e6),
    '| Transaction and monitoring fees received (fund level)         ' + f(r.pfee * 1e6),
    '| Management fee offsets                                        (' + f(r.off * 1e6) + ')',
    '| Management fee, net                                            ' + f(r.net * 1e6),
    '',
    'Partnership expenses',
    '| Partnership expenses (LP share)                                ' + f(0.35 * SHARE * 1e6)
  ];
  if (i === 3) {
    lines.push('', 'Capital account since inception (LP share)',
      '| Capital contributions                                          ' + f(contrib * 1e6),
      '| Distributions                                                  ' + f(dist * 1e6),
      '| Net asset value before accrued carried interest                ' + f(nav * 1e6),
      '', 'Carried interest', '| Accrued carried interest, LP share (Section 9.4)              ' + f(naiveCarry * 1e6),
      'Accrued carried interest is calculated as 20% of cumulative net gains at reported value.',
      '', 'Performance since inception (fund level, net)', '| Net IRR ' + (perf.irr * 100).toFixed(1) + '%   Net TVPI ' + perf.tvpi.toFixed(2) + 'x   DPI ' + perf.dpi.toFixed(2) + 'x');
  }
  docs[id] = { title: 'Quarterly report, ' + labels[i], kind: 'report', pages: [lines] };
});
fs.writeFileSync(root + 'assets/data/fta-docs.js', '/* Synthetic documents for the Fund Terms Auditor: a fictional LPA excerpt and four quarterly reports.\n   Generated once by tools/gen-fta.mjs from the fund data; three breaks are planted on purpose. The hand-set\n   ground truth is in assets/data/fta-labels.js. */\nwindow.FTA_DOCS = ' + JSON.stringify(docs, null, 1) + ';\n');
console.log({ perf, contrib: contrib.toFixed(3), dist: dist.toFixed(3), nav: nav.toFixed(3), naiveCarry: naiveCarry.toFixed(4), rep: rep.map(r => [r.q, r.nic, r.gross.toFixed(6), r.off.toFixed(6), r.net.toFixed(6)]) });
