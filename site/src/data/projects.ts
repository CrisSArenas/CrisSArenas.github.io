import raw from './projects.json';
import stats from '../../../assets/data/card-stats.json';

export type AreaId = 'portfolio' | 'quant' | 'ai' | 'private' | 'lab';
export interface DocLink { title: string; href: string }
export interface Project {
  slug: string; stat: string; area: AreaId; kind: string; featured: boolean; title: string; href: string; summary: string; tags: string[];
  memo?: DocLink; note?: DocLink;
}
export interface LabItem { slug: string; title: string; kind: string; group: string; href: string; summary: string; tags: string[] }
export interface CardStat { value: string; label: string; demo: string; chart: { type: string; [k: string]: unknown } }

export const AREAS = raw.areas as Record<AreaId, { label: string; blurb: string }>;
export const PROJECTS = raw.projects as Project[];
export const LAB = raw.lab as LabItem[];
/* key numbers computed by each application at its base case (regenerated by tools/card-stats.mjs) */
export const STATS = (stats as unknown as { cards: Record<string, CardStat> }).cards;
export const statFor = (p: Project): CardStat | undefined => STATS[p.stat];
export const bySlug = (slug: string) => PROJECTS.find(p => p.slug === slug);
export const FEATURED = PROJECTS.filter(p => p.featured);
